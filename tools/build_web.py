"""PlatformIO pre-build step: bundle web/ into one gzipped page in src/web_assets.h.

web/index.html references style.css and js/*.js; they are inlined so the
browser needs a single request (lwIP on the device allows five TCP
connections in total). The header only changes when the page does.
"""
import gzip
import hashlib
import os
import re
import sys

try:
    Import("env")  # noqa: F821  (PlatformIO)
    ROOT = env["PROJECT_DIR"]  # noqa: F821
except NameError:
    ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

WEB = os.path.join(ROOT, "web")
OUT = os.path.join(ROOT, "src", "web_assets.h")


def read(rel):
    with open(os.path.join(WEB, rel), encoding="utf-8") as f:
        return f.read()


def bundle():
    html = read("index.html")

    def css(m):
        return "<style>\n" + read(m.group(1)) + "\n</style>"

    def js(m):
        src = read(m.group(1))
        return "<script>\n" + src.replace("</script", "<\\/script") + "\n</script>"

    html = re.sub(r'<link rel="stylesheet" href="([^"]+)">', css, html)
    html = re.sub(r'<script src="([^"]+)"></script>', js, html)
    return html.encode("utf-8")


def main():
    raw = bundle()
    gz = gzip.compress(raw, compresslevel=9, mtime=0)
    etag = hashlib.sha1(raw).hexdigest()[:16]
    lines = [
        "// Generated by tools/build_web.py from web/ - do not edit.",
        "#pragma once",
        "#include <stdint.h>",
        f'#define WEB_ETAG "{etag}"',
        f"static const uint32_t WEB_INDEX_RAW_LEN = {len(raw)};",
        f"static const uint32_t WEB_INDEX_GZ_LEN = {len(gz)};",
        "static const uint8_t WEB_INDEX_GZ[] = {",
    ]
    for i in range(0, len(gz), 20):
        lines.append("  " + ",".join(str(b) for b in gz[i:i + 20]) + ",")
    lines.append("};")
    text = "\n".join(lines) + "\n"
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
    if old != text:
        with open(OUT, "w", encoding="utf-8") as f:
            f.write(text)
    print(f"web: {len(raw)} bytes -> {len(gz)} gzipped, etag {etag}")


main()
